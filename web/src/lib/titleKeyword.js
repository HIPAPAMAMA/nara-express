// 정부 공고 제목엔 "2026년"·"하반기"·"[수의시담]" 같은 연도·구분 표기가 자주 붙는데, 이걸 그대로
// 검색어로 쓰면 다른 해/다른 표기의 관련 공고와 안 겹친다 — 레이더류 위젯의 "공고 검색" 버튼에서
// 핵심 사업명만 뽑아내는 데 재사용한다.
export function toSearchKeyword(title) {
  return title
    .replace(/^\[[^\]]*\]\s*/, '')
    .replace(/^\d{4}년(도)?\s*/, '')
    .replace(/^(상|하)반기\s*/, '')
    .replace(/^\d{4}년(도)?\s*/, '')
    .trim();
}
